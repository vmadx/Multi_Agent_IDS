"""
Shared State & Data Schemas for Multi-Agent Network Intrusion Detection System.
Compatible with LangGraph StateGraph, Pydantic v2, and MongoDB serialization.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Dict, List, Optional, Any, TypedDict
from pydantic import BaseModel, Field
import uuid


# ==========================================
# 1. ENUMS FOR SYSTEM-WIDE CONSISTENCY
# ==========================================

class SeverityLevel(str, Enum):
    BENIGN = "BENIGN"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ActionType(str, Enum):
    BLOCK_IP = "BLOCK_IP"
    RATE_LIMIT = "RATE_LIMIT"
    ISOLATE_HOST = "ISOLATE_HOST"
    DROP_SESSION = "DROP_SESSION"
    ALERT_ANALYST = "ALERT_ANALYST"


class ExecutionStatus(str, Enum):
    PENDING = "PENDING"
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


class EscalationLevel(str, Enum):
    NONE = "NONE"
    SUBNET_BAN = "SUBNET_BAN"
    RATE_LIMIT_PORT = "RATE_LIMIT_PORT"
    EMERGENCY_QUARANTINE = "EMERGENCY_QUARANTINE"
    TIER2_NOTIFY = "TIER2_NOTIFY"


# ==========================================
# 2. CORE DATA MODELS (PYDANTIC)
# ==========================================

class NetworkEvent(BaseModel):
    """Normalized network telemetry event ingested by the Monitoring Agent."""
    event_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    src_ip: str
    dst_ip: str
    src_port: int
    dst_port: int
    protocol: str  # TCP, UDP, ICMP, etc.
    duration: float = 0.0  # connection duration in seconds
    packet_count: int = 1
    byte_count: int = 0
    flags: Optional[str] = None  # e.g., 'SYN', 'ACK', 'FIN'
    raw_features: Dict[str, Any] = Field(default_factory=dict)  # NSL-KDD / CICIDS2017 raw columns


class TriagedAlert(BaseModel):
    """Pre-processed and filtered alert generated by the Triage Agent."""
    alert_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    event_id: str
    src_ip: str
    dst_ip: str
    dst_port: int
    urgency_score: float = Field(ge=0.0, le=1.0)  # 0.0 (safe) to 1.0 (imminent critical threat)
    severity: SeverityLevel
    category: str  # e.g., 'DDoS', 'PortScan', 'Brute-Force', 'Suspicious', 'Benign'
    is_duplicate: bool = False
    reason: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class ResponseAction(BaseModel):
    """Individual defensive countermeasure."""
    action_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    action_type: ActionType
    target: str  # IP address, port, or subnet CIDR
    priority: int = 1  # 1 = highest execution priority
    parameters: Dict[str, Any] = Field(default_factory=dict)  # e.g., {'duration_sec': 3600, 'rate_kbps': 500}


class ResponsePlan(BaseModel):
    """Collection of actions generated by Response Planning & approved by HITL."""
    plan_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    alert_id: str
    actions: List[ResponseAction] = Field(default_factory=list)
    approved_by: Optional[str] = "SYSTEM_AUTOPILOT"  # or Analyst name if HITL
    approved_at: Optional[datetime] = None


class ExecutionResult(BaseModel):
    """Outcome of an individual executed response action."""
    action_id: str
    action_type: ActionType
    target: str
    status: ExecutionStatus
    executed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    error_message: Optional[str] = None


class VerificationResult(BaseModel):
    """Closed-loop post-execution check output from Verification Agent."""
    verification_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    plan_id: str
    target_ip: str
    threat_cleared: bool
    confidence: float = Field(ge=0.0, le=1.0)
    post_action_packet_rate: float
    observed_drop_percentage: float
    details: str
    checked_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class EscalationDecision(BaseModel):
    """Decision produced by Adapt & Escalate Agent when threat persists."""
    escalation_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    plan_id: str
    target_ip: str
    escalation_level: EscalationLevel
    adapted_actions: List[ResponseAction] = Field(default_factory=list)
    escalation_count: int = 1
    reason: str
    requires_tier2_human: bool = False
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# ==========================================
# 3. SHARED LANGGRAPH AGENT STATE
# ==========================================

class AgentState(TypedDict, total=False):
    """
    Central LangGraph State Dictionary passed across all nodes in the multi-agent graph.
    All team members (Phani, Madhuri, Hima) read from and write to this state.
    """
    # Telemetry & Ingestion (Phani - Monitoring & Triage)
    current_event: Optional[Dict[str, Any]]
    current_alert: Optional[Dict[str, Any]]
    
    # ML Detection & Diagnosis (Madhuri)
    ml_prediction: Optional[str]
    ml_confidence: Optional[float]
    ml_probabilities: Optional[Dict[str, float]]
    diagnosis_hypothesis: Optional[str]
    xai_explanation: Optional[str]

    # RAG, Planning & Approval (Hima)
    retrieved_mitre_context: Optional[str]
    response_plan: Optional[Dict[str, Any]]
    hitl_approved: bool

    # Execution & Verification (Phani - Execution, Verification, Escalation)
    execution_results: List[Dict[str, Any]]
    verification_result: Optional[Dict[str, Any]]
    escalation_decision: Optional[Dict[str, Any]]
    escalation_count: int

    # Lifecycle & Audit
    status: str  # 'INGESTED', 'TRIAGED', 'DETECTED', 'DIAGNOSED', 'EXECUTED', 'VERIFIED', 'RESOLVED', 'ESCALATED'
    audit_logs: List[str]
